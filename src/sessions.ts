import type { Stats } from 'node:fs'
import { homedir } from 'node:os'

export interface TokenUsage {
  input: number
  output: number
  cacheRead: number
  cacheWrite: number
}

export type HarnessId = 'claude' | 'omp'

export interface Session {
  harness: HarnessId
  sessionId: string
  title: string | null // set by the user
  aiTitle: string | null // generated by the harness
  cwd: string
  gitBranch: string | null
  firstUserMessage: string | null
  lastUserMessage: string | null
  contextTokens: number | null
  models: Record<string, TokenUsage>
  totals: TokenUsage
  throughput: number
  searchText: string
  mtime: number
  lastTimestamp: number
  filePath: string
}

export interface Message {
  role: 'user' | 'assistant'
  text: string
  timestamp?: string
}

export interface SessionFile {
  harness: HarnessId
  filePath: string
  stats: Stats
}

export type TrashFn = (paths: string | readonly string[]) => Promise<void>

// One agent harness clod reads sessions from. Each owns its storage layout,
// transcript format, and how it renames, deletes, and resumes a session.
export interface Harness {
  id: HarnessId
  name: string
  mark: string
  listFiles: () => Promise<SessionFile[]>
  parse: (file: SessionFile) => Promise<Session | null>
  messages: (session: Session) => Promise<Message[]>
  resume: (session: Session) => { command: string; args: string[] }
  rename: (session: Session, title: string) => Promise<void>
  delete: (session: Session) => Promise<void>
}

// Real throughput: new tokens processed + generated, excluding cache re-reads.
// Matches the figure shown in the shell status line.
export function throughputOf(usage: Partial<TokenUsage>): number {
  return (usage.input || 0) + (usage.output || 0) + (usage.cacheWrite || 0)
}

export function modelKey(modelId: string | undefined): 'opus' | 'sonnet' | 'haiku' | null {
  if (!modelId) return null
  if (modelId.includes('opus')) return 'opus'
  if (modelId.includes('sonnet')) return 'sonnet'
  if (modelId.includes('haiku')) return 'haiku'
  return null
}

export const MONTHS = [
  'Jan',
  'Feb',
  'Mar',
  'Apr',
  'May',
  'Jun',
  'Jul',
  'Aug',
  'Sep',
  'Oct',
  'Nov',
  'Dec'
]

export function relativeTime(ms: number): string {
  const now = new Date()
  const then = new Date(ms)
  const sameDay =
    now.getFullYear() === then.getFullYear() &&
    now.getMonth() === then.getMonth() &&
    now.getDate() === then.getDate()

  if (sameDay) {
    const diff = Date.now() - ms
    if (diff < 60000) return 'now'
    const mins = Math.floor(diff / 60000)
    if (mins < 60) return `${mins}m`
    return `${Math.floor(mins / 60)}h`
  }

  const label = `${MONTHS[then.getMonth()]} ${then.getDate()}`
  return then.getFullYear() === now.getFullYear() ? label : `${label} ${then.getFullYear()}`
}

export function shortPath(p: string): string {
  return p.replace(homedir(), '~')
}

export function fmtTokens(n: number): string {
  if (n >= 1e9) return `${(n / 1e9).toFixed(1)}B`
  if (n >= 1e6) return `${(n / 1e6).toFixed(1)}M`
  if (n >= 1e3) return `${Math.round(n / 1e3)}k`
  return String(n)
}
